for (const [year, days] of Object.entries(expected)) {
    test(`${year}년 공휴일이 공표된 날짜와 같다`, () => {
        expect(Object.fromEntries(holidaysFor(Number(year)))).toEqual(days);
    });
}

test('2025년 어린이날은 부처님오신날과 겹쳐서 대체공휴일이 하루 생긴다', () => {
    const h = holidaysFor(2025);
    expect(h.get('2025-05-05')).toBe('부처님오신날·어린이날'); // 겹친 날은 이름을 이어 붙인다
    expect(h.get('2025-05-06')).toBe('어린이날 대체공휴일');
    expect([...h.values()].filter(v => v.includes('대체공휴일')).length).toBe(3); // 삼일절·어린이날·추석
});

test('2028년 개천절은 추석 당일과 겹쳐서, 연휴를 건너뛴 다음 평일이 대체공휴일이 된다', () => {
    expect(holidaysFor(2028).get('2028-10-05')).toBe('개천절 대체공휴일');
});

test('설날·추석 연휴는 토요일과 겹쳐도 대체공휴일이 없다 (일요일만 해당)', () => {
    // 2026 추석 연휴 9/24(목)~9/26(토) — 토요일이 끼지만 대체공휴일 없음
    const h = holidaysFor(2026);
    expect([...h.values()].filter(v => v.startsWith('추석 대체'))).toEqual([]);
});

test('신정과 현충일은 주말과 겹쳐도 대체공휴일이 없다', () => {
    // 2028-01-01 은 토요일, 2027-06-06 은 일요일
    expect(holidaysFor(2028).get('2028-01-03')).toBeUndefined();
    expect([...holidaysFor(2027).values()].filter(v => v.includes('현충일 대체'))).toEqual([]);
});

test('제헌절은 2026년부터만 공휴일이다', () => {
    expect(holidaysFor(2025).get('2025-07-17')).toBeUndefined();
    expect(holidaysFor(2026).get('2026-07-17')).toBe('제헌절');
});

test('표에 없는 연도는 양력 고정일만 나온다', () => {
    const h = holidaysFor(2035);
    expect(h.get('2035-01-01')).toBe('신정');
    expect([...h.values()].some(v => v.includes('설날'))).toBe(false);
});

test('holidaysForRange는 해를 넘겨도 모은다', () => {
    const h = holidaysForRange('2026-12-01', '2027-01-31');
    expect(h.get('2026-12-25')).toBe('성탄절');
    expect(h.get('2027-01-01')).toBe('신정');
});
